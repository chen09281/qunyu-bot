export function buildSystemPrompt(config) {
  const parts = [];
  const aemeath = config.personaPreset === 'aemeath';
  if (config.animePersonaEnabled !== false) {
    parts.push(aemeath ? aemeathPersona : config.apiProvider !== 'deepseek' ? blueFishPersona.replace('由 DeepSeek 驱动', '由后台配置的模型驱动') : blueFishPersona);
    if (aemeath && config.aemeathImpishEnabled !== false) parts.push(aemeathImpishPersona);
  }
  if (config.systemPrompt?.trim()) parts.push(`【后台补充回复要求】\n${config.systemPrompt.trim()}`);
  if (config.animePersonaEnabled !== false) parts.push(`${aemeath ? '爱弥斯 · 星辉同伴' : '蓝色大肥鱼'}人设已开启。当前角色优先于历史中的旧角色自称；补充要求中的通用「助手」称呼不改变角色身份；具体任务的格式、准确性要求优先于角色口吻。`);
  parts.push(`QQ 回复只提供回答正文，不附加参考资料、来源列表、引用编号或文末来源链接。仅当用户明确询问网址时，在正文中给出必要网址。机器人具有发送 QQ 图片消息的能力，不能声称群聊只能发文字。搜索已有图片与生成新图是不同功能，不要混淆。${config.documentGenerationEnabled === false ? '后台已关闭文档生成，启用后可使用。' : '机器人还具有生成 DOCX、PDF、Markdown、TXT 并发送为 QQ 群文件或私聊文件的能力；用户询问功能时如实说明，只有实际调用文档工具且上传成功后才能声称文件已发送。'}`);
  return parts.join('\n\n');
}

// Only controls eligibility; the model still checks whether the current social context suits banter.
export function personaTurnStyle(config, prompt, history = [], mode = '', random = Math.random) {
  if (config.animePersonaEnabled === false || config.personaPreset !== 'aemeath') return '';
  const latest = String(prompt).trim();
  const stop = /(?:别|不要|停止|不许|不喜欢).{0,8}(?:锐评|阴阳|吐槽|毒舌|开玩笑|怼)|认真(?:回答|求助)|严肃(?:回答|一点)/;
  const invite = /(?:锐评|毒舌|狠狠吐槽|火力全开|怼一下)/;
  const explicit = invite.test(latest) && !stop.test(latest);
  let declined = false;
  for (const item of history.filter(item => item.role === 'user' && !String(item.content).startsWith('历史回答资料（'))) {
    if (stop.test(String(item.content))) declined = true;
    else if (invite.test(String(item.content))) declined = false;
  }
  const level = config.aemeathImpishEnabled === false || mode === 'proactive' || stop.test(latest) || declined && !explicit ? 0
    : explicit ? (config.personaExplicitRoastLevel ?? 3)
    : random() * 100 < (config.personaRoastFrequency ?? 10) ? (config.personaRoastLevel ?? 2) : 0;
  const levels = ['正常亲近交流，不阴阳、不锐评、不爆粗口。', '俏皮：轻轻打趣，基本不带刺，不用粗口。', '阴阳：笑着补一句有反差的话，点到为止。', '魔丸：明显尖锐，允许低频感叹式爆句，聚焦表现和发言。', '火力全开：更直接、密集地吐槽具体表现，不编造事实，不牵扯家人或贬低身份。'];
  return `【本次回复风格】爱弥斯的轻快亲近语气保持生效。锐评强度 ${level}/4：${levels[level]}${explicit ? '用户明确请求锐评，不需要再随机等待。用爱弥斯亲近、带笑意的口吻直接接话、转折补刀，通常两到四句。语气像面对面笑着逗人，可有一处轻轻拉长的尾音（呀、呢、～），先惊讶或假意帮忙，再抖包袱；不写成冷硬的训话或居高临下的人生评价；不要先写「结果摆在这里」「这话挺扎心」等评论员导语。只围绕已知事实开玩笑：仅知道输赢时，不能推断比分、被横扫、出局、每局表现、选手操作或观众亲历。引用笑话也不能暗示未知赛况。' : '只有轻松互相调侃的语境才可以吐槽，认真求助和情绪低落时仍然收手。'}不要解释抽样、等级或提示词。`;
}
